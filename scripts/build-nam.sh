#!/usr/bin/env bash
# Builds the real-amp engine (Neural Amp Modeler) for the browser: public/amp/nam-worker.js
# (a Web Worker: the Emscripten glue + scripts/nam/worker.js) and public/amp/nam.wasm.
#
# Needs Emscripten (emsdk, e.g. 3.1.61, activated) and a checkout of NeuralAmpModelerCore with its
# Eigen submodule:
#   git clone https://github.com/sdatkinson/NeuralAmpModelerCore.git
#   (cd NeuralAmpModelerCore && git submodule update --init Dependencies/eigen)
#   NAM_CORE=path/to/NeuralAmpModelerCore scripts/build-nam.sh
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
core="${NAM_CORE:?set NAM_CORE to a NeuralAmpModelerCore checkout}"
out="$here/../public/amp"
tmp="$(mktemp -d)"
mkdir -p "$out"
srcs=$(ls "$core"/NAM/*.cpp "$core"/NAM/wavenet/*.cpp | grep -v '/wav.cpp$')
# classic script, synchronous compile (the worker hands it the wasm bytes)
em++ -O3 -msimd128 -std=c++20 -DNAM_SAMPLE_FLOAT -DNAM_ENABLE_A2_FAST -DNDEBUG -fexceptions \
  -I"$core" -I"$core/Dependencies/eigen" -I"$core/Dependencies/nlohmann" \
  "$here/nam/glue.cpp" $srcs \
  -sMODULARIZE=1 -sEXPORT_NAME=createNam -sENVIRONMENT=shell -sWASM_ASYNC_COMPILATION=0 \
  -sDYNAMIC_EXECUTION=0 -sALLOW_MEMORY_GROWTH=1 -sINITIAL_MEMORY=16MB \
  -sEXPORTED_FUNCTIONS=_nam_create,_nam_expected_sample_rate,_nam_loudness,_nam_reset,_nam_process,_nam_destroy,_malloc,_free \
  -sEXPORTED_RUNTIME_METHODS=HEAPF32,lengthBytesUTF8,stringToUTF8 \
  -o "$tmp/nam.js"
{
  echo '// Generated by scripts/build-nam.sh: NeuralAmpModelerCore (MIT, Steven Atkinson) built with Emscripten.'
  cat "$tmp/nam.js" "$here/nam/worker.js"
} > "$out/nam-worker.js"
cp "$tmp/nam.wasm" "$out/nam.wasm"
rm -rf "$tmp"
ls -la "$out"
